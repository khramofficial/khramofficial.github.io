/* Writes supabase/seed.sql from src/data/seed.ts (upserts, safe to re-run). Run: npx jiti scripts/make-seed-sql.ts */
import { writeFileSync } from "node:fs";
import { collectionToRow, productToRow } from "../src/lib/catalog";
import { seedCollections, seedProducts, seedSettings } from "../src/data/seed";

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  return `'${String(v).replace(/'/g, "''")}'`;
};
const arr = (a: string[] | null | undefined) => (a == null ? "null" : `array[${a.map(q).join(", ")}]::text[]`);
const json = (v: unknown) => (v == null ? "null" : `${q(JSON.stringify(v))}::jsonb`);

function upsert(table: string, row: Record<string, unknown>, key: string, kinds: Record<string, "arr" | "json">) {
  const cols = Object.keys(row).filter((c) => c !== "updated_at" && c !== "created_at");
  const vals = cols.map((c) => (kinds[c] === "arr" ? arr(row[c] as string[]) : kinds[c] === "json" ? json(row[c]) : q(row[c])));
  const set = cols.filter((c) => c !== key).map((c) => `${c} = excluded.${c}`);
  return `insert into public.${table} (${cols.join(", ")})\nvalues (${vals.join(", ")})\non conflict (${key}) do update set ${set.join(", ")};\n`;
}

const cKinds = { description: "arr", swatch: "json", i18n: "json" } as const;
const pKinds = {
  notes: "arr", description: "arr", included: "arr", how_it_works: "arr", sample_prompts: "arr",
  specs: "json", outline: "json", faq: "json", cover: "json", gallery: "json", i18n: "json",
} as const;

let sql = "-- Khram seed data (generated by scripts/make-seed-sql.ts). Safe to re-run.\nbegin;\n";
for (const c of seedCollections) sql += upsert("collections", collectionToRow(c) as unknown as Record<string, unknown>, "slug", cKinds);
for (const p of seedProducts) sql += upsert("products", productToRow(p) as unknown as Record<string, unknown>, "slug", pKinds);
sql += `insert into public.site_settings (id, data) values (1, ${json(seedSettings)}) on conflict (id) do update set data = excluded.data;\n`;
sql += "commit;\n";
writeFileSync("supabase/seed.sql", sql);
console.log(`seed.sql: ${seedCollections.length} collections, ${seedProducts.length} products, ${sql.length} chars`);
